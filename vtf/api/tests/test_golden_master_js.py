"""Golden Master Test Suite — JS ↔ Python parity (AC-1.3).

This is the REAL parity test. It loads golden_cases_js.json — generated by
running the actual JavaScript estimateSejourTotal() via generate_js_golden_master.mjs
— and asserts that the Python service produces identical results (±1€).

The existing test_golden_master.py validates Python internal consistency
(Python vs Python). This file validates the thing that matters for AC-1.3:
that porting the JS to Python didn't silently break any calculation.

SETUP (one-time)
----------------
From vtf/front/:

    npx tsx generate_js_golden_master.mjs \\
        --out ../api/tests/golden_cases_js.json

Or for a quick spot-check on 3 villages:

    npx tsx generate_js_golden_master.mjs \\
        --villages biarritz,agde,chamonix \\
        --out ../api/tests/golden_cases_js.json

The file is committed to the repo so CI doesn't need Node.js installed.
Re-generate whenever the JS estimateSejourTotal changes.

RUN
---
    pytest tests/test_golden_master_js.py -v
    pytest tests/test_golden_master_js.py -v -k "biarritz"
    pytest tests/test_golden_master_js.py -v -k "ete"
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest
from django.core.management import call_command

from apps.pricing.services.stay_estimate import estimate_sejour_total

# ── Load data ─────────────────────────────────────────────────────────────────

_FIXTURE_DIR = Path(__file__).resolve().parent.parent / "apps" / "catalog" / "fixtures"
_TESTS_DIR   = Path(__file__).resolve().parent

_JS_CASES_FILE = _TESTS_DIR / "golden_cases_js.json"

# If the JS golden master hasn't been generated yet, skip the whole module
# rather than error. This lets CI pass even before the first npm run.
if not _JS_CASES_FILE.exists():
    pytest.skip(
        reason=(
            "golden_cases_js.json not found. Generate it with:\n"
            "  cd vtf/front && npx tsx generate_js_golden_master.mjs "
            "--out ../api/tests/golden_cases_js.json"
        ),
        allow_module_level=True,
    )

with _JS_CASES_FILE.open(encoding="utf-8") as _fh:
    JS_GOLDEN_CASES: list[dict] = json.load(_fh)

# Village fixture
with (_FIXTURE_DIR / "villages.json").open(encoding="utf-8") as _fh:
    _VILLAGE_FIXTURE = json.load(_fh)

# Pricing rules
with (_FIXTURE_DIR / "pricing_rules.json").open(encoding="utf-8") as _fh:
    _PR_DATA = json.load(_fh)

PRICING_RULES: dict = _PR_DATA[0]["fields"]["payload"]

# Meals catalog
with (_FIXTURE_DIR / "meals.json").open(encoding="utf-8") as _fh:
    _MEALS_RAW = json.load(_fh)

MEALS_CATALOG: list[dict] = [
    {
        "code":        m["pk"],
        "label":       m["fields"]["label"],
        "price_adult": m["fields"]["price_adult"],
        "price_child": m["fields"]["price_child"],
    }
    for m in _MEALS_RAW
]

_VILLAGES_RAW: dict[str, dict] = {
    d["pk"]: d["fields"]
    for d in _VILLAGE_FIXTURE
    if d["model"] == "catalog.village"
}

# ── Helpers ───────────────────────────────────────────────────────────────────

def _village_for_case(case: dict) -> dict | None:
    vid = case["input"]["villageId"]
    raw = _VILLAGES_RAW.get(vid)
    if raw is None:
        return None
    # Map fixture snake_case fields → camelCase expected by the Python service.
    # The service reads village.get("bebeClub"), village.get("qfExc") etc.
    # Without this mapping those fields resolve to None → False, causing wrong
    # child discount fractions and QF rates on villages with bebeClub or qfExc.
    return {
        "id":          vid,
        "nom":         raw.get("nom", ""),
        "region":      raw.get("region", ""),
        "formules":    raw.get("formules", []),
        "hasLoc":      raw.get("has_loc", False),
        "ski":         raw.get("ski", False),
        "ouverture":   raw.get("ouverture", ""),
        "tarifs":      raw.get("tarifs", {}),
        "bebeClub":    raw.get("bebe_club", False),    # ← was missing
        "forfaitRM":   raw.get("forfait_rm", False),
        "qfExc":       raw.get("qf_exc", False),        # ← was missing
        "enfSoloHalf": raw.get("enf_solo_half", False),
    }


def _assert_within(field: str, actual: int, expected: int, case_id: str) -> None:
    diff = abs(actual - expected)
    assert diff <= 1, (
        f"[{case_id}] {field}: Python={actual}, JS={expected}, diff={diff}€ "
        f"(tolerance ±1€ per AC-1.3)"
    )


# ── DB fixtures ────────────────────────────────────────────────────────────────
#
# estimate_sejour_total() reads MarketingSeasons from the DB (winter QF
# eligibility window). Without loading this fixture, pytest-django's empty
# test DB makes that lookup return nothing, silently changing the QF gate's
# behaviour from what runs against the real dev DB. This loads the same
# marketing_seasons fixture load_vtf_mocks uses elsewhere in the suite
# (see tests/test_phase1.py's `loaded_db`) — no application logic changes.

@pytest.fixture(scope="module", autouse=True)
def _marketing_seasons_loaded(django_db_setup, django_db_blocker):
    with django_db_blocker.unblock():
        call_command(
            "loaddata",
            str(_FIXTURE_DIR / "marketing_seasons.json"),
            verbosity=0,
        )
    yield


# ── Parametrised test ─────────────────────────────────────────────────────────

@pytest.mark.django_db
@pytest.mark.parametrize("case", JS_GOLDEN_CASES, ids=[c["id"] for c in JS_GOLDEN_CASES])
def test_js_python_parity(case):
    """
    AC-1.3: Python estimate_sejour_total must match JS estimateSejourTotal ±1€.

    Each parametrised case was produced by running the actual TypeScript
    source (not compiled, via tsx) so it reflects the exact JS Math.round()
    behaviour, including any rounding differences the JS implementation has.
    """
    village = _village_for_case(case)
    if village is None:
        pytest.skip(f"Village {case['input']['villageId']!r} not in fixture")

    family  = case["input"]["family"]
    sejour  = case["input"]["sejour"]
    exp     = case["expected"]

    # Run the Python service
    result = estimate_sejour_total(
        family=family,
        sejour=sejour,
        village=village,
        pricing_rules=PRICING_RULES,
        meals_catalog=MEALS_CATALOG,
    )

    assert result is not None, (
        f"[{case['id']}] Python service returned None — JS returned total={exp['total']}"
    )

    cid = case["id"]

    # Primary money fields — ±1€ tolerance
    _assert_within("total",           result.total,            exp["total"],           cid)
    _assert_within("perPerson",       result.per_person,       exp["perPerson"],       cid)
    _assert_within("totalAdults",     result.total_adults,     exp["totalAdults"],     cid)
    _assert_within("totalChildren",   result.total_children,   exp["totalChildren"],   cid)
    _assert_within("perAdultBase",    result.per_adult_base,   exp["perAdultBase"],    cid)
    _assert_within("staySubtotal",    result.stay_subtotal,    exp["staySubtotal"],    cid)
    _assert_within("adhesion",        result.adhesion,         exp["adhesion"],        cid)
    _assert_within("transportTotal",  result.transport_total,  exp["transportTotal"],  cid)
    _assert_within("restoTotal",      result.resto_total,      exp["restoTotal"],      cid)
    _assert_within("activitiesTotal", result.activities_total, exp["activitiesTotal"], cid)

    # Non-money fields — exact match
    assert result.saison_key == exp["saisonKey"], (
        f"[{cid}] saisonKey: Python={result.saison_key!r}, JS={exp['saisonKey']!r}"
    )
    assert result.nuits == exp["nuits"], (
        f"[{cid}] nuits: Python={result.nuits}, JS={exp['nuits']}"
    )

    # Discount rate — allow ±0.001 float diff
    assert abs(result.discount_rate - exp["discountRate"]) <= 0.001, (
        f"[{cid}] discountRate: Python={result.discount_rate}, JS={exp['discountRate']}"
    )

    # Child lines — count and amounts
    assert len(result.child_lines) == len(exp.get("childLines", [])), (
        f"[{cid}] childLines count: Python={len(result.child_lines)}, JS={len(exp.get('childLines', []))}"
    )
    for i, (py_line, js_line) in enumerate(zip(result.child_lines, exp.get("childLines", []))):
        assert py_line.age == js_line["age"], (
            f"[{cid}] childLines[{i}].age: Python={py_line.age}, JS={js_line['age']}"
        )
        _assert_within(
            f"childLines[{i}].amount",
            py_line.amount,
            js_line["amount"],
            cid,
        )
        assert abs(py_line.discount_fraction - js_line["discount_fraction"]) <= 0.001, (
            f"[{cid}] childLines[{i}].discountFraction: "
            f"Python={py_line.discount_fraction}, JS={js_line['discount_fraction']}"
        )


# ── Summary helper ────────────────────────────────────────────────────────────

def test_golden_cases_js_file_has_minimum_cases():
    """Sanity: the JS golden master file must have at least 10 cases."""
    assert len(JS_GOLDEN_CASES) >= 10, (
        f"golden_cases_js.json only has {len(JS_GOLDEN_CASES)} cases. "
        f"Re-generate with: npx tsx generate_js_golden_master.mjs --out tests/golden_cases_js.json"
    )


def test_all_cases_have_required_fields():
    """Every case must have id, input, expected with the required keys."""
    required_input_keys  = {"villageId", "family", "sejour"}
    required_expect_keys = {"total", "perPerson", "saisonKey", "nuits", "staySubtotal"}

    for case in JS_GOLDEN_CASES:
        assert "id" in case, f"Case missing 'id': {case}"
        assert required_input_keys <= set(case.get("input", {}).keys()), (
            f"Case {case.get('id')} missing input keys"
        )
        assert required_expect_keys <= set(case.get("expected", {}).keys()), (
            f"Case {case.get('id')} missing expected keys"
        )
